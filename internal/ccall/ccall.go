// Package ccall calls C functions and lets C call Go functions, for the
// native modules the xs package loads, without the reflection and the
// allocations a general foreign-function interface needs: every function
// either way takes integer arguments (C integers and pointers) and returns
// one integer.
//
// A call into C runs the function on the thread's system stack through
// runtime.cgocall, with its arguments in a Call that lives in memory the
// caller keeps (so that nothing is allocated for it). A call from C enters
// through a small assembly trampoline that saves the argument registers and
// goes to Go through crosscall2 and runtime.cgocallback, the way C code
// generated by cgo calls Go; a Go function indexes a table with the
// trampoline's number and calls the registered function. On architectures
// without such trampolines here, the same API is served by
// github.com/ebitengine/purego.
//
// The trampoline technique follows github.com/ebitengine/purego (Apache
// License 2.0), whose dynamic loading and runtime support (fakecgo, which
// provides crosscall2 when cgo is off) go-perl uses as well.
package ccall

import "sync"

// MaxArgs is the number of integer arguments a callback registered with
// NewCallback may take, and MaxCallArgs the number a C function called
// through this package may take (the integer argument registers of every
// supported architecture).
const (
	MaxArgs     = 8
	MaxCallArgs = 6
)

// Args are the arguments of a call from C: Args[i] is argument i as the
// register (or stack slot) that carries it. An argument narrower than 64
// bits (a C int) leaves the upper bits unspecified: convert it, as
// int32(args[i]).
type Args [MaxArgs]uintptr

// Call is a call into C: the function, its arguments and its result. It
// must live in memory that outlives the call, such as a field of a value
// the caller keeps: C code reads the arguments from it and writes the
// result into it, after the Go code it calls back may have moved the
// goroutine's stack. (A Call declared as a local variable escapes to the
// heap for that reason, and is allocated for every call.)
type Call struct {
	fn   uintptr
	args [MaxCallArgs]uintptr
	ret  uintptr
}

// Invoke calls the C function fn with up to MaxCallArgs integer arguments
// on the system stack and returns its result.
func (c *Call) Invoke(fn uintptr, args ...uintptr) uintptr {
	if len(args) > MaxCallArgs {
		panic("ccall: too many arguments")
	}
	c.fn = fn
	n := copy(c.args[:], args)
	clear(c.args[n:])
	c.ret = 0
	invoke(c)
	return c.ret
}

// calls keeps Calls for Invoke.
var calls = sync.Pool{New: func() any { return new(Call) }}

// Invoke calls the C function fn with up to MaxCallArgs integer arguments,
// with a Call of its own that is reused afterwards, and returns its result.
func Invoke(fn uintptr, args ...uintptr) uintptr {
	c := calls.Get().(*Call)
	r := c.Invoke(fn, args...)
	calls.Put(c)
	return r
}
