//go:build darwin || linux

// Package ccall calls C functions and lets C call Go functions, for the
// native modules the xs package loads, without the reflection and the
// allocations a general foreign-function interface needs: every function
// either way takes integer arguments (C integers and pointers) and returns
// one integer.
//
// The functions are those whose signature the caller fixes: the entry
// points of go-perl's XS SDK (a native module's own functions — its XSUBs,
// pp, magic, PerlIO, keyword and destructor functions — are reached through
// one of them), functions of the C library, and the SDK's calls back into
// Go, with at most MaxCallArgs arguments into C and MaxArgs back. A native
// module's own C functions, whose signatures the package cannot know, are
// not called through it; a function with more arguments, floating-point
// arguments, or a struct argument or result is out of its scope.
//
// A call into C runs the function on the thread's system stack through
// runtime.cgocall, with its arguments in a Call that lives in memory the
// caller keeps, so that on amd64 and arm64 nothing is allocated for it. A
// call from C enters through a small assembly trampoline that saves the
// argument registers and goes to Go through crosscall2 and
// runtime.cgocallback, the way C code generated by cgo calls Go; a Go
// function indexes a table with the trampoline's number and calls the
// registered function. On architectures
// without such trampolines here, the same API is served by
// github.com/ebitengine/purego, whose calls allocate.
//
// The trampoline technique follows github.com/ebitengine/purego (Apache
// License 2.0), whose dynamic loading and runtime support (fakecgo, which
// provides crosscall2 when cgo is off) go-perl uses as well.
package ccall

import (
	"fmt"
	"sync"
)

// MaxArgs is the number of integer arguments a callback registered with
// NewCallback may take: the eight argument registers of arm64, and on
// amd64 its six argument registers and the first two stack slots of the
// C caller. MaxCallArgs is the number a C function called through this
// package may take: the integer argument registers common to amd64 and
// arm64.
const (
	MaxArgs     = 8
	MaxCallArgs = 6
)

// Args are the arguments of a call from C: Args[i] is argument i as the
// register (or stack slot) that carries it. An argument narrower than 64
// bits (a C int) leaves the upper bits unspecified: convert it, as
// int32(args[i]). The callback reads them and does not keep them: on amd64
// Args[6] and Args[7] are the C caller's stack slots, which are not the
// callback's to write.
type Args [MaxArgs]uintptr

// MaxCallbacks is the number of callbacks NewCallback makes in a process.
// A callback is made for good, since C may keep its address, and on amd64
// and arm64 each is an entry of a table of trampolines in the program's
// code (ccall_<arch>.s), whose size is fixed when the program is built.
// The number is the table's size, a choice and not a count of anything:
// callbacks are for the entry points a program gives C once, at startup,
// and a program that needs more than the table holds gets NewCallback's
// error from the start.
const MaxCallbacks = 64

var (
	// callbacksMu guards callbackN, the number of callbacks made.
	callbacksMu sync.Mutex
	callbackN   int
)

// NewCallback returns the address of a C function that calls fn with its
// arguments (at most MaxArgs integers) and returns fn's result. It fails
// once MaxCallbacks callbacks have been made.
func NewCallback(fn func(args *Args) uintptr) (uintptr, error) {
	callbacksMu.Lock()
	defer callbacksMu.Unlock()
	if callbackN == MaxCallbacks {
		return 0, fmt.Errorf("ccall: all %d callbacks have been made", MaxCallbacks)
	}
	entry := newCallback(callbackN, fn)
	callbackN++
	return entry, nil
}

// Call is a call into C: the function, its arguments and its result. It
// must live in memory that outlives the call, such as a field of a value
// the caller keeps: C code reads the arguments from it and writes the
// result into it, after the Go code it calls back may have moved the
// goroutine's stack. (A Call declared as a local variable escapes to the
// heap for that reason, and is allocated for every call.) A Call holds one
// call: it makes one Invoke at a time, and a callback that calls C while
// an Invoke of a Call waits for it uses a Call of its own.
type Call struct {
	fn   uintptr
	args [MaxCallArgs]uintptr
	ret  uintptr
}

// Invoke calls the C function fn with up to MaxCallArgs integer arguments
// on the system stack and returns its result. A result narrower than 64
// bits (a C int) leaves the upper bits unspecified: convert it, as
// int32(r). Its arguments are integers
// and addresses of memory that is not Go's (C's, or a mapping): Go memory
// may move or be freed while the call runs, so a pointer to it goes
// through the package's Invoke, or is pinned (runtime.Pinner) for the call.
// (The //go:uintptrescapes that keeps such memory would put every call's
// arguments on the heap, and a Call is there to allocate nothing.)
func (c *Call) Invoke(fn uintptr, args ...uintptr) uintptr {
	if fn == 0 {
		panic("ccall: call of a nil C function")
	}
	if len(args) > MaxCallArgs {
		panic("ccall: too many arguments")
	}
	c.fn = fn
	n := copy(c.args[:], args)
	clear(c.args[n:])
	c.ret = 0
	invoke(c)
	return c.ret
}

// calls keeps Calls for Invoke.
var calls = sync.Pool{New: func() any { return new(Call) }}

// Invoke calls the C function fn with up to MaxCallArgs integer arguments,
// with a Call of its own that is reused afterwards, and returns its result
// as (*Call).Invoke does. An argument converted from a pointer to Go
// memory in the call, uintptr(unsafe.Pointer(p)), keeps that memory where
// it is and alive until the call returns.
//
//go:uintptrescapes
func Invoke(fn uintptr, args ...uintptr) uintptr {
	c := calls.Get().(*Call)
	r := c.Invoke(fn, args...)
	calls.Put(c)
	return r
}
