// callbackAsm is entered from C with the call's arguments in R0-R7 and
// the trampoline's number in R12. It saves the argument registers, builds
// a callbackFrame and calls callbackWrap through crosscall2 and
// runtime.cgocallback, as C code generated by cgo calls Go, and returns
// the frame's result to C in R0.
//
// Its frame, 16-byte aligned: R27 (which the assembler uses as a scratch
// register and the C calling convention preserves) and R30 at 0, the
// callbackFrame at 16 (index, args, result), padding at 40, and the eight
// argument registers at 48, the block the frame's args points to.
TEXT callbackAsm<>(SB), NOSPLIT|NOFRAME, $0
	NO_LOCAL_POINTERS
	SUB	$(8*8), RSP, R14
	STP	(R0, R1), (0*8)(R14)
	STP	(R2, R3), (2*8)(R14)
	STP	(R4, R5), (4*8)(R14)
	STP	(R6, R7), (6*8)(R14)
	SUB	$(6*8+8*8), RSP
	STP	(R27, R30), (0*8)(RSP)
	ADD	$(2*8), RSP, R13
	MOVD	R12, (0*8)(R13)
	MOVD	R14, (1*8)(R13)
	MOVD	ZR, (2*8)(R13)
	MOVD	·callbackWrapCall(SB), R0
	MOVD	(R0), R0 // fn: callbackWrap's entry
	MOVD	R13, R1 // frame
	MOVD	$0, R3 // ctxt
	BL	crosscall2(SB)
	ADD	$(2*8), RSP, R13
	MOVD	(2*8)(R13), R0
	LDP	(0*8)(RSP), (R27, R30)
	ADD	$(6*8+8*8), RSP
	RET

// callCAsm is what runtime.cgocall runs on the system stack (asmcgocall
// calls it as a C function with the *Call in R0): it calls the Call's
// function with its arguments, R19 (callee-saved) holding the Call, and
// stores the result. Call: fn at 0, args at 8..48, ret at 56.
TEXT callCAsm<>(SB), NOSPLIT|NOFRAME, $0
	SUB	$16, RSP
	STP	(R19, R30), (0*8)(RSP)
	MOVD	R0, R19
	MOVD	(0*8)(R19), R9
	MOVD	(1*8)(R19), R0
	MOVD	(2*8)(R19), R1
	MOVD	(3*8)(R19), R2
	MOVD	(4*8)(R19), R3
	MOVD	(5*8)(R19), R4
	MOVD	(6*8)(R19), R5
	BL	(R9)
	MOVD	R0, (7*8)(R19)
	LDP	(0*8)(RSP), (R19, R30)
	ADD	$16, RSP
	RET

