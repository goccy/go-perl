// callbackAsm is entered from C with the call's arguments in DI, SI, DX,
// CX, R8, R9 and on the C caller's stack, under the return address of the
// trampoline's CALL. It puts the six registers over the C caller's return
// address (kept in R10), right below the arguments on the stack, so that
// they make one block of arguments; builds a callbackFrame and calls
// callbackWrap through crosscall2 and runtime.cgocallback, as C code
// generated by cgo calls Go; and returns the frame's result to C in AX.
// crosscall2 saves and restores the registers the C calling convention
// preserves; callbackAsm saves the two it changes before that: BP, which
// it makes the frame pointer of its frame, and R15, which the assembler
// uses to reach a global symbol when the program is linked dynamically.
// The stack pointer is 16-byte aligned at the call of crosscall2, as at a
// C call.
TEXT callbackAsm<>(SB), NOSPLIT|NOFRAME, $0
	MOVQ	0(SP), AX // the trampoline's return address
	MOVQ	8(SP), R10 // the C caller's return address
	ADDQ	$8, SP
	ADJSP	$(5*8), SP
	MOVQ	DI, (0*8)(SP)
	MOVQ	SI, (1*8)(SP)
	MOVQ	DX, (2*8)(SP)
	MOVQ	CX, (3*8)(SP)
	MOVQ	R8, (4*8)(SP)
	MOVQ	R9, (5*8)(SP)
	MOVQ	SP, R8 // the block of arguments
	PUSHQ	R10
	ADJSP	$(2*8), SP
	MOVQ	BP, (1*8)(SP)
	LEAQ	(1*8)(SP), BP
	MOVQ	R15, (0*8)(SP)
	// the trampoline's number: its return address is the next one's
	MOVQ	$callbackTable<>(SB), DX
	SUBQ	DX, AX
	MOVQ	$0, DX
	MOVQ	$5, CX
	DIVL	CX
	SUBQ	$1, AX
	// the callbackFrame
	SUBQ	$(3*8), SP
	MOVQ	AX, (0*8)(SP)
	MOVQ	R8, (1*8)(SP)
	MOVQ	$0, (2*8)(SP)
	MOVQ	SP, SI // frame
	MOVQ	·callbackWrapCall(SB), DI
	MOVQ	(DI), DI // fn: callbackWrap's entry
	MOVQ	$0, CX // ctxt
	CALL	crosscall2(SB)
	MOVQ	(2*8)(SP), AX
	ADDQ	$(3*8), SP
	MOVQ	(0*8)(SP), R15
	MOVQ	(1*8)(SP), BP
	ADJSP	$-(2*8), SP
	POPQ	R10
	ADJSP	$-(5*8), SP
	MOVQ	R10, 0(SP)
	RET

// callCAsm is what runtime.cgocall runs on the system stack (asmcgocall
// calls it as a C function with the *Call in DI, the stack 16-byte
// aligned): it calls the Call's function with its arguments, BX
// (callee-saved) holding the Call, and stores the result. Call: fn at 0,
// args at 8..48, ret at 56.
TEXT callCAsm<>(SB), NOSPLIT|NOFRAME, $0
	PUSHQ	BP
	MOVQ	SP, BP
	PUSHQ	BX
	SUBQ	$8, SP
	MOVQ	DI, BX
	MOVQ	(0*8)(BX), R11
	MOVQ	(1*8)(BX), DI
	MOVQ	(2*8)(BX), SI
	MOVQ	(3*8)(BX), DX
	MOVQ	(4*8)(BX), CX
	MOVQ	(5*8)(BX), R8
	MOVQ	(6*8)(BX), R9
	XORL	AX, AX
	CALL	R11
	MOVQ	AX, (7*8)(BX)
	ADDQ	$8, SP
	POPQ	BX
	POPQ	BP
	RET

