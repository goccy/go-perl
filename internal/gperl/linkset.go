package gperl

// The link set: how a project's dependencies enter a Go build.
//
// The go-perl package imports github.com/goccy/go-perl/cpan, an empty
// package. For a project, gperl generates a module with the same import
// path that carries the dependencies —
//
//	lib.zip                     every distribution's module tree (go:embed)
//	static.go    (cgo)          imports each distribution's native package
//	                            and registers its entry tables
//	dynamic_<goos>_<goarch>.go  (no cgo) embeds the .so files instead
//
// — and a Go workspace file that puts it, and the native packages of the
// distributions, in front of the build. A program that imports go-perl
// needs no change: built with the workspace it carries the dependencies.

import (
	"archive/zip"
	"crypto/sha256"
	"encoding/hex"
	"errors"
	"fmt"
	"io"
	"io/fs"
	"maps"
	"os"
	"path/filepath"
	"slices"
	"sort"
	"strings"

	"github.com/goccy/go-perl/internal/mod"
)

// linkSet is a generated link set.
type linkSet struct {
	cpanDir  string   // the generated go-perl/cpan module
	distDirs []string // the native packages of the distributions
}

// goWorkHeader marks a workspace file as gperl's to rewrite.
const goWorkHeader = "// Code generated by gperl from cpanfile.snapshot. DO NOT EDIT.\n"

// writeProjectGoWork writes go.work in a project directory that is a Go
// module, so that plain go commands there build with the project's
// dependencies. A project that is not a Go module, or has no
// dependencies, gets none; a go.work gperl did not write is left alone
// and reported.
func writeProjectGoWork(m *mod.Manager, projectDir, target string, deps *projectDeps) error {
	projectDir, err := filepath.Abs(projectDir)
	if err != nil {
		return err
	}
	if !fileExists(filepath.Join(projectDir, "go.mod")) || len(deps.lib) == 0 {
		return nil
	}
	path := filepath.Join(projectDir, "go.work")
	existing, err := os.ReadFile(path)
	if err != nil && !errors.Is(err, fs.ErrNotExist) {
		return err
	}
	if err == nil && !strings.HasPrefix(string(existing), goWorkHeader) {
		return fmt.Errorf("%s exists and was not written by gperl; remove it, or add the module directories it needs yourself", path)
	}
	links, err := generateLinkSet(m, deps)
	if err != nil {
		return err
	}
	if err := links.writeGoWork(path, "."); err != nil {
		return err
	}
	fmt.Fprintf(os.Stderr, "gperl: wrote %s (%d native packages)\n", path, len(links.distDirs))
	if strings.HasSuffix(target, muslSuffix) && len(links.distDirs) > 0 {
		fmt.Fprintf(os.Stderr, "gperl: the native modules are built for musl: build with go build -tags %s\n", muslTag)
	}
	return nil
}

// writeGoWork writes a workspace file at path that builds mainDir with the
// link set.
func (l *linkSet) writeGoWork(path, mainDir string) error {
	var b strings.Builder
	b.WriteString(goWorkHeader + "\ngo 1.25.0\n\nuse (\n")
	for _, dir := range append([]string{mainDir, l.cpanDir}, l.distDirs...) {
		fmt.Fprintf(&b, "\t%q\n", dir)
	}
	b.WriteString(")\n")
	return os.WriteFile(path, []byte(b.String()), 0o644)
}

// generateLinkSet writes the link set of deps under the module directory,
// keyed by what it carries and the gperl that writes it, and returns it;
// an up-to-date one is reused.
func generateLinkSet(m *mod.Manager, deps *projectDeps) (*linkSet, error) {
	natives := map[string][]nativeModule{} // by tree
	for _, tree := range deps.trees {
		modules, err := nativeModules(tree)
		if err != nil {
			return nil, err
		}
		if len(modules) > 0 {
			natives[tree] = modules
		}
	}
	key := sha256.New()
	fmt.Fprintf(key, "%s\n", mod.GperlVersion())
	for _, tree := range deps.trees {
		fmt.Fprintf(key, "%s\n", tree)
		for _, n := range natives[tree] {
			fmt.Fprintf(key, "  %s %s\n", n.target, n.archive)
		}
	}
	l := &linkSet{cpanDir: filepath.Join(m.Dir, "cache", "linkset", hex.EncodeToString(key.Sum(nil)[:8]), "cpan")}
	for _, tree := range deps.trees {
		if len(natives[tree]) > 0 {
			l.distDirs = append(l.distDirs, mod.ABIDir(tree))
		}
	}
	done := filepath.Join(l.cpanDir, "generated")
	if fileExists(done) {
		return l, nil
	}
	if err := os.RemoveAll(l.cpanDir); err != nil {
		return nil, err
	}
	if err := os.MkdirAll(l.cpanDir, 0o755); err != nil {
		return nil, err
	}
	// The module tree goes in as one archive: go:embed takes no files
	// outside the module, nor two names that differ only in case, which
	// perl's module trees can hold.
	if err := writeLibZip(deps.lib, filepath.Join(l.cpanDir, "lib.zip")); err != nil {
		return nil, err
	}
	files := map[string]string{
		"go.mod":  "module " + cpanModulePath + "\n\ngo 1.25.0\n",
		"cpan.go": linkSetLib,
	}
	var static strings.Builder
	static.WriteString("// Code generated by gperl. DO NOT EDIT.\n\n//go:build cgo\n\npackage cpan\n\nimport (\n\t\"unsafe\"\n\n\t\"github.com/goccy/go-perl/xs\"\n\n")
	i := 0
	for _, tree := range deps.trees {
		if len(natives[tree]) > 0 {
			fmt.Fprintf(&static, "\td%d %q\n", i, distImportPath(tree))
			i++
		}
	}
	static.WriteString(")\n\nfunc init() {\n\tfor _, entries := range []map[string]unsafe.Pointer{")
	for j := 0; j < i; j++ {
		fmt.Fprintf(&static, "d%d.Entries, ", j)
	}
	static.WriteString("} {\n\t\tfor module, entry := range entries {\n\t\t\txs.Register(module, entry)\n\t\t}\n\t}\n}\n")
	if i > 0 {
		files["static.go"] = static.String()
	}

	// Without cgo the binary carries the .so files of its own target.
	targets := map[string]bool{}
	for _, tree := range deps.trees {
		for _, n := range natives[tree] {
			so := strings.TrimSuffix(n.archive, ".a") + ".so"
			src := filepath.Join(mod.TargetDir(tree, n.target), filepath.FromSlash(so))
			if err := linkOrCopy(src, filepath.Join(l.cpanDir, "native", n.target, filepath.FromSlash(so))); err != nil {
				return nil, err
			}
			targets[n.target] = true
		}
	}
	for target := range targets {
		dynamic := strings.ReplaceAll(linkSetDynamic, "TARGET", target)
		files["dynamic_"+target+".go"] = strings.ReplaceAll(dynamic, "TAGS", strings.Join(targetTags(target), " && "))
	}
	names := make([]string, 0, len(files))
	for name := range files {
		names = append(names, name)
	}
	sort.Strings(names)
	for _, name := range names {
		if err := os.WriteFile(filepath.Join(l.cpanDir, name), []byte(files[name]), 0o644); err != nil {
			return nil, err
		}
	}
	return l, os.WriteFile(done, nil, 0o644)
}

// linkSetLib is the generated package's unconditional half: the module
// tree.
const linkSetLib = `// Code generated by gperl. DO NOT EDIT.

// Package cpan carries a project's CPAN dependencies into a binary.
package cpan

import (
	"archive/zip"
	"bytes"
	_ "embed"

	"github.com/goccy/go-perl/internal"
)

//go:embed lib.zip
var lib []byte

func init() {
	tree, err := zip.NewReader(bytes.NewReader(lib), int64(len(lib)))
	if err != nil {
		panic(err)
	}
	internal.SetCPANLib(tree)
}
`

// writeLibZip writes the files of lib into a zip archive at path, in name
// order and stored as they are (the tree is read whole at every start, see
// internal.UnpackTree).
func writeLibZip(lib map[string]string, path string) (err error) {
	f, err := os.Create(path)
	if err != nil {
		return err
	}
	defer func() { err = errors.Join(err, f.Close()) }()
	zw := zip.NewWriter(f)
	for _, name := range slices.Sorted(maps.Keys(lib)) {
		w, err := zw.CreateHeader(&zip.FileHeader{Name: name, Method: zip.Store})
		if err != nil {
			return err
		}
		src, err := os.Open(lib[name])
		if err != nil {
			return err
		}
		_, err = io.Copy(w, src)
		if err := errors.Join(err, src.Close()); err != nil {
			return err
		}
	}
	return zw.Close()
}

// linkSetDynamic is the generated package's cgo-less half for one target:
// the loadable modules, as files.
const linkSetDynamic = `// Code generated by gperl. DO NOT EDIT.

//go:build !cgo && TAGS

package cpan

import (
	"embed"
	"io/fs"

	"github.com/goccy/go-perl/internal"
	_ "github.com/goccy/go-perl/xs"
)

//go:embed all:native/TARGET
var native embed.FS

func init() {
	tree, err := fs.Sub(native, "native/TARGET")
	if err != nil {
		panic(err)
	}
	internal.SetXSNative(tree)
}
`

// linkOrCopy makes dst a copy of src, as a hard link when the file system
// allows one.
func linkOrCopy(src, dst string) error {
	if err := os.MkdirAll(filepath.Dir(dst), 0o755); err != nil {
		return err
	}
	if err := os.Link(src, dst); err == nil || errors.Is(err, fs.ErrExist) {
		return nil
	}
	return copyFileMode(src, dst)
}
