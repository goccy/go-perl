package main

import (
	"reflect"
	"strings"
	"testing"
)

func TestNameservers(t *testing.T) {
	conf := `# Generated by Docker Engine.
nameserver 192.168.5.4
nameserver fd00::1
options ndots:0
 nameserver   10.0.0.2  # trailing words
nameserver
search example.com
`
	if got, want := nameservers(conf), []string{"192.168.5.4", "10.0.0.2"}; !reflect.DeepEqual(got, want) {
		t.Errorf("nameservers: %v; want %v", got, want)
	}
}

func TestConverseAnswersOfflineRequestsOnly(t *testing.T) {
	in := `make: Entering directory
{"request":"offline"}
{"request":"online"}
{"phase":"test"}
not json {"request":"offline"}
`
	var log strings.Builder
	offline := 0
	converse(strings.NewReader(in), &log, func() { offline++ })
	if offline != 1 {
		t.Errorf("offline asked %d times; want once", offline)
	}
	want := "make: Entering directory\n{\"request\":\"online\"}\n{\"phase\":\"test\"}\nnot json {\"request\":\"offline\"}\n"
	if log.String() != want {
		t.Errorf("log %q; want %q", log.String(), want)
	}
}

func TestOutcomeOfOfflineFailure(t *testing.T) {
	res := &result{Phases: []phaseRecord{{Phase: "unpack"}, {Phase: "configure"}, {Phase: "prerequisites"},
		{Phase: "build"}, {Phase: "offline", Status: 1}}}
	if outcome, installed := outcomeOf(res, false); outcome != outcomeDriverFailed || installed {
		t.Errorf("network not taken away: %s, installed %v; want driver_failed", outcome, installed)
	}
}
